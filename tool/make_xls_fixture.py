"""生成测试用的合成课表固件 `test/fixtures/sample_timetable.xls`。

为什么要合成：原来的固件是作者**本人真实教务系统导出**的 .xls（含真实课程名、
教师、教室），放在公开仓库里不合适，所以换成内容全虚构、**结构完全对齐**的一份。

对齐的是「真实教务系统导出长什么样」这件事：
* 8 行 × 9 列：第 0 行表头（学期 / 课表名 / 专业），第 1 行 `节次` + 星期一到星期日，
  第 2~6 行是 5 个大节（上午 / 下午 / 晚上 × 节次一~五），最后一整行是 `注--` 页脚；
* 单元格文本格式 `课程/(节次)周次/ 地点/教师/课程代码/教学班`；
* 一格多课时用 `\\r\\n` 分隔；
* 覆盖单周 `(单)` / 双周 `(双)`、跨周次区间、同格连排三门课这些分支。

真实文件里的合并单元格在读取时表现为「每个被合并的格子里都是同一段文字」，
所以这里干脆逐格写同样的文字（不声明合并），保证 `XlsReader` 读出来的网格与原来一致。

依赖：`pip install xlwt`（写老式 .xls / BIFF8）。用法：
    python tool/make_xls_fixture.py
"""

import os

import xlwt

SEMESTER = "2026-2027年第1学期"
SHEET_NAME = "演示26.8课表"
MAJOR = "专业：示例工程"

# (课程名, 教师, 地点, 课程代码)
COURSES = {
    "甲": ("示例课程甲", "示例老师A", "格致楼201", "AA0000001-01"),
    "乙": ("示例课程乙", "示例老师B", "格致楼202", "AA0000002-02"),
    "丙": ("示例课程丙", "示例老师C", "格致楼203", "AA0000003-03"),
    "丁": ("示例课程丁", "示例老师D", "格致楼204", "AA0000004-04"),
    "戊": ("示例课程戊", "示例老师E", "明德楼A101", "AA0000005-05"),
    "己": ("示例课程己", "示例老师F", "实验楼101", "AA0000006-06"),
    "庚": ("示例课程庚", "示例老师G", "明德楼A102", "AA0000007-07"),
    "辛": ("示例课程辛", "示例老师H", "田径场01", "AA0000008-08"),
    "壬": ("示例课程壬", "示例老师I", "明德楼A103", "AA0000009-09"),
    "癸": ("示例课程癸", "示例老师J", "格致楼205", "AA0000010-10"),
}


def cell(key, sections, weeks, room=None, classes="演示26.8"):
    """拼一个单元格：`课程/(节次)周次/ 地点/教师/课程代码/教学班`。"""
    name, teacher, default_room, code = COURSES[key]
    return "{0}/({1}节){2}/ {3}/{4}/(2026-2027-1)-{5}/{6}".format(
        name, sections, weeks, room or default_room, teacher, code, classes
    )


# (行, 列) → 单元格文本；列 2~8 依次是星期一~星期日
CELLS = {
    # 第 2 大节行（上午，节次一）：周一 1-2 / 周三 1-2 / 周四 1-2 / 周五 1-2
    (2, 2): cell("甲", "1-2", "7-18周"),
    (2, 4): cell("乙", "1-2", "7-18周", classes="演示26.7;演示26.8"),
    (2, 5): cell("丙", "1-2", "6-18周", classes="演示26.7;演示26.8"),
    (2, 6): cell("丁", "1-2", "7-10周", classes="演示26.7;演示26.8"),
    # 第 3 大节行（上午，节次二）：周一 / 周三 3-4，周四 3-4，周五 3-4
    (3, 2): cell("戊", "3-4", "7-18周"),
    (3, 4): cell("戊", "3-4", "7-18周", room="明德楼A104"),
    (3, 5): cell("己", "3-4", "6-18周", room="实验楼102"),
    (3, 6): cell("庚", "3-4", "7-17周", room="明德楼A105"),
    # 第 4 大节行（下午，节次三）：周二 5-6 单双周互补，周三 / 周四 / 周五
    (4, 3): "\r\n".join([
        cell("乙", "5-6", "7-17周(单)", room="格致楼206"),
        cell("丙", "5-6", "8-12周(双)", room="明德楼A106"),
    ]),
    (4, 4): cell("己", "5-6", "7-18周", room="实验楼103"),
    (4, 5): cell("辛", "5-6", "1-18周", classes="演示26.7;演示26.8"),
    (4, 6): "\r\n".join([
        cell("壬", "5-6", "7-10周", room="明德楼A107"),
        cell("己", "5-6", "11-17周", room="实验楼104"),
    ]),
    # 第 5 大节行（下午，节次四）：周二 7-8，周四 7-8 连排三门，周五 7-8
    (5, 3): cell("甲", "7-8", "7-18周", room="格致楼207"),
    (5, 5): "\r\n".join([
        cell("癸", "7-8", "6-10周", room="格致楼208",
             classes="演示26.1;演示26.2;演示26.8"),
        cell("庚", "7-8", "11-15周", room="明德楼A108"),
        cell("戊", "7-8", "16-18周", room="明德楼A109"),
    ]),
    (5, 6): cell("戊", "7-8", "6-18周", room="明德楼A110"),
    # 第 6 大节行（晚上，节次五）：周一 9-10 双周
    (6, 2): cell("乙", "9-10", "12-14周(双)", room="格致楼209",
                 classes="演示26.7;演示26.8"),
}

# 第 0 行：学期 / 课表名 / 专业（真实文件里这三段分别跨了几列，读取时逐格重复）
ROW0 = [SEMESTER] * 3 + [SHEET_NAME] * 4 + [MAJOR] * 2
ROW1 = ["节次", "", "星期一", "星期二", "星期三", "星期四", "星期五", "星期六", "星期日"]
# 第 1 列是节次序号（一~五），第 0 列是时段
ROW_LABELS = {
    2: ("上午", "一"), 3: ("上午", "二"),
    4: ("下午", "三"), 5: ("下午", "四"),
    6: ("晚上", "五"),
}
FOOTER = (
    "注--内容顺序为：课程<>周次<>地点<>教师<>教学班<>教学班组成          "
    "本学期2026-08-31正式上课至2027-01-17结束，共20周.                     "
    "打印时间：2026-08-31"
)


def main():
    book = xlwt.Workbook(encoding="utf-8")
    sheet = book.add_sheet("课表")

    for col, text in enumerate(ROW0):
        sheet.write(0, col, text)
    for col, text in enumerate(ROW1):
        if text:
            sheet.write(1, col, text)

    for row, (period, index) in ROW_LABELS.items():
        sheet.write(row, 0, period)
        sheet.write(row, 1, index)

    for (row, col), text in CELLS.items():
        sheet.write(row, col, text)

    sheet.write(7, 0, FOOTER)

    out = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "test", "fixtures", "sample_timetable.xls",
    )
    book.save(out)
    print("wrote", out, os.path.getsize(out), "bytes")


if __name__ == "__main__":
    main()
